"""Full-year held-out eval across all 4 building types vs OUR OWN RBC baseline.

THE standard evaluation protocol: one complete EnergyPlus year (105_120 steps =
8760 h x 12 steps/h) per building, rolled to episode termination.

Contrast eval_transfer_panel.py, which scores only the first 672 steps -- 2.33 days
of January, ~0.6% of a year. That window systematically FLATTERS the policy: it beat
RBC there while losing over the full year. Treat the chunk as a smoke test, not a result.

Baselines come from data/rbc_fullyear_ourharness.json (computed by this same harness),
never from the published scores table -- see OUR_BASELINES below for why.

    python scripts/eval_fullyear_panel.py --checkpoint runs/transfer4_persistent_mid/model_s0.eqx

Writes data/<tag>_fullyear_eval.csv and data/baseline_fullyear.csv for the figure.
"""
import argparse
import json
import multiprocessing as mp
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "vendor", "morel"))
sys.path.insert(0, os.path.join(REPO, "vendor", "Building2Building"))
sys.path.insert(0, os.path.join(REPO, "scripts"))
os.environ.setdefault("WANDB_MODE", "offline")

import _pin_dataset  # noqa: F401
import numpy as np
import pandas as pd

from building2building.data.registry import get_registry
from morel_amorpheus import amorpheus_policy
from morel_b2b_amorpheus import (AMORPHEUS_B2B_BRIDGE, AMORPHEUS_B2B_SPE_BRIDGE,
                                 AMORPHEUS_B2B_SPE_UNIVERSE, load_model)
from morel.morphology import trivial_morphology
from evaluate import _b2b_factory_impl

# bridge name -> (bridge, universe-for-load_model); mirrors dagger_stream
BRIDGES = {"plain": (AMORPHEUS_B2B_BRIDGE, None),
           "spe": (AMORPHEUS_B2B_SPE_BRIDGE, AMORPHEUS_B2B_SPE_UNIVERSE)}

TYPES = ["RetailStandalone", "RestaurantFastFood", "OfficeMedium", "OfficeSmall"]
TASK, RP, N, MAX_STEPS = "task_occ_e0", "full_year", 5, 106000  # full year = 105_120 steps

# Baselines we computed OURSELVES through this same harness.
#
# Do NOT use building2building/scores/baseline_returns.csv here. Measured on
# identical buildings, its RBC scores are 2.27-3.40x SMALLER in magnitude than ours
# (e.g. RestaurantFastFood-3997: table -2261.9 vs ours -7701.4) -- almost certainly a
# different timesteps_per_hour. Comparing against it made the policy look ~3x worse
# than RBC when like-for-like it is far closer. Only ever compare against numbers
# generated by the same harness.
OUR_BASELINES = os.path.join(REPO, "data", "rbc_fullyear_ourharness.json")


def _worker(args):
    """Spawn-pool worker: one full-year rollout in its own process (EnergyPlus-safe).
    Top-level + picklable so it survives spawn."""
    ckpt, bt, idx, split, task, bridge, clamp_oa, oa_floor = args
    ret, steps = policy_return(ckpt, bt, idx, split, task, bridge, clamp_oa,
                               oa_floor)
    return bt, idx, ret, steps


def policy_return(ckpt, bt, idx, split="test", task=TASK, bridge="plain",
                  clamp_oa=None, oa_floor=None):
    env, source = _b2b_factory_impl(bt, idx, split, task, RP)
    if oa_floor is not None:
        # constrained-domain checkpoint: its [-1,1] OA output is typed against
        # the FLOORED source (Range(floor, high)) — rebuild the source to match
        from morel_b2b import b2b_morphology, normalize_b2b
        source = normalize_b2b().apply(b2b_morphology(env, oa_floor=oa_floor))
    br, universe = BRIDGES[bridge]
    lens = br.apply(trivial_morphology(source))
    sp = amorpheus_policy(load_model(ckpt, d_model=64, n_heads=4, n_layers=3,
                                     universe=universe))(br.apply(source))
    an = [str(n).lower() for n in env.metadata["action_names"]]
    oa_i = np.array([i for i, n in enumerate(an)
                     if "outdoor air controller" in n and "mass flow" in n])
    raw, _ = env.reset()
    ret, steps = 0.0, 0
    for _t in range(MAX_STEPS):
        tca, tpa = sp(*lens.split_observation(source.split_observation(raw)))
        a = np.asarray(source.join_actions(lens.join_actions((tca, tpa))), dtype=np.float64)
        if clamp_oa is not None and oa_i.size:
            a[oa_i] = np.maximum(a[oa_i], clamp_oa)
        raw, r, term, trunc, _ = env.step(a)
        ret += float(r); steps += 1
        if term or trunc:
            break
    env.close()
    return ret, steps


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--checkpoint", required=True)
    ap.add_argument("--tag", default="transfer4_mid")
    ap.add_argument("--n-workers", type=int, default=3,
                    help="parallel rollout processes (one building each)")
    ap.add_argument("--building-types", nargs="+", default=None,
                    help="restrict to these types (default: all four)")
    ap.add_argument("--split", default="test",
                    help="dataset split to evaluate on (test or train)")
    ap.add_argument("--task", default=TASK,
                    help="b2b task preset (e.g. task_occ_emed for energy)")
    ap.add_argument("--bridge", default="plain", choices=list(BRIDGES),
                    help="spe for checkpoints trained with the spectral-PE bridge")
    ap.add_argument("--clamp-oa-min", type=float, default=None,
                    help="safety-layer projection: floor Outdoor Air Controller "
                         "mass-flow commands at this value (kg/s)")
    ap.add_argument("--oa-floor", type=float, default=None,
                    help="checkpoint was TRAINED on the OA-floored domain: "
                         "decode actions against the floored source typing")
    ap.add_argument("--baselines", default=OUR_BASELINES,
                    help="JSON {building_id: baseline_return} to compare against "
                         "(default: our test default-RBC baseline)")
    args = ap.parse_args()
    if args.building_types is not None:
        global TYPES
        TYPES = args.building_types
    ckpt = args.checkpoint if os.path.isabs(args.checkpoint) else os.path.join(REPO, args.checkpoint)

    with open(args.baselines) as f:
        base = json.load(f)
    reg = get_registry()

    # idx-major ordering => the first wave is one building of EACH type, so a
    # first cross-type read arrives early instead of after all of Retail.
    tasks = [(ckpt, bt, idx, args.split, args.task, args.bridge,
              args.clamp_oa_min, args.oa_floor)
             for idx in range(N) for bt in TYPES]
    ids = {(bt, idx): reg.get_building_by_index(bt, args.split, idx).building_id
           for bt in TYPES for idx in range(N)}

    rows, brows = [], []
    print(f"[eval] {len(tasks)} full-year rollouts | {args.n_workers} parallel "
          f"processes | one-per-type first", flush=True)
    with mp.get_context("spawn").Pool(processes=args.n_workers) as pool:
        for k, (bt, idx, p, steps) in enumerate(
                pool.imap_unordered(_worker, tasks), 1):
            bid = ids[(bt, idx)]
            rb = base.get(bid, float("nan"))
            rows.append({"building_type": bt, "building_id": bid,
                         "episode_return": p, "n_steps": steps, "seed": 0})
            brows.append({"building_type": bt, "building_id": bid,
                          "baseline_return": rb})
            print(f"  [{k:2d}/{len(tasks)}] {bid:26s} policy {p:10.1f}  "
                  f"RBC {rb:10.1f}  ({steps} steps)  "
                  f"{'POLICY' if p > rb else 'rbc'}", flush=True)

    df = pd.DataFrame(rows); bdf = pd.DataFrame(brows)
    out = os.path.join(REPO, "data", f"{args.tag}_fullyear_eval.csv")
    bout = os.path.join(REPO, "data", "baseline_fullyear.csv")
    df.to_csv(out, index=False); bdf.to_csv(bout, index=False)

    print("\n=== SUMMARY (full year) ===")
    tot = 0
    for bt in TYPES:
        s = df[df.building_type == bt]; sb = bdf[bdf.building_type == bt]
        w = int((s.episode_return.to_numpy() > sb.baseline_return.to_numpy()).sum())
        tot += w
        norm = (s.episode_return.to_numpy() / sb.baseline_return.to_numpy()).mean()
        print(f"  {bt:22s} policy {s.episode_return.mean():10.1f}  "
              f"RBC {sb.baseline_return.mean():10.1f}  norm {norm:.3f}  wins {w}/{N}")
    print(f"  TOTAL wins: {tot}/{len(TYPES)*N}")
    print(f"[done] {out}\nEVAL_DONE")


if __name__ == "__main__":
    main()
